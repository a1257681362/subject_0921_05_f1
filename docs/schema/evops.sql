-- H2 本地文件数据库初始化脚本。
-- 连锁眼镜店系统 F1：镜片基础信息 + 加工单（含左右眼处方）+ 操作日志。
-- 约定：所有业务表一律逻辑删除（deleted=1），不做物理删除；
--       每次写入留存 operator / request_no / biz_time / version_no。

CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

-- 镜片基础信息
CREATE TABLE IF NOT EXISTS t_lens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lens_code VARCHAR(32) NOT NULL,
    lens_name VARCHAR(64) NOT NULL,
    brand VARCHAR(64),
    lens_type VARCHAR(32),
    unit_price DECIMAL(10, 2) NOT NULL DEFAULT 0,
    remark VARCHAR(255),
    deleted INT NOT NULL DEFAULT 0,                          -- 0 生效 / 1 已冲销（恢复置 0）
    version_no BIGINT NOT NULL DEFAULT 0,                 -- 乐观锁版本号
    operator VARCHAR(64) NOT NULL,                        -- 最后操作人
    request_no VARCHAR(64) NOT NULL,                      -- 最后写入请求号
    biz_time TIMESTAMP NOT NULL,                          -- 最后写入业务时间
    create_by VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(64),
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_lens_code UNIQUE (lens_code)
);

-- 加工单
CREATE TABLE IF NOT EXISTS t_process_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(32) NOT NULL,
    customer_name VARCHAR(64) NOT NULL,
    customer_phone VARCHAR(32),
    store_code VARCHAR(32),
    lens_id BIGINT,                                       -- 选用镜片
    status VARCHAR(16) NOT NULL DEFAULT 'CREATED',        -- CREATED/PROCESSING/READY/PICKED/CANCELLED
    remark VARCHAR(255),
    deleted INT NOT NULL DEFAULT 0,
    version_no BIGINT NOT NULL DEFAULT 0,
    operator VARCHAR(64) NOT NULL,
    request_no VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    create_by VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(64),
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_process_order_no UNIQUE (order_no)
);

-- 处方（加工单关联表，左眼 L / 右眼 R，与加工单同生共死）
CREATE TABLE IF NOT EXISTS t_prescription (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    eye CHAR(1) NOT NULL,                                 -- L 左眼 / R 右眼
    sphere DECIMAL(5, 2),                                 -- 球镜 S，25度一档
    cylinder DECIMAL(5, 2),                               -- 柱镜 C，25度一档
    axis INT,                                             -- 轴位 A，1~180
    pd DECIMAL(4, 1),                                     -- 瞳距 mm
    deleted INT NOT NULL DEFAULT 0,
    version_no BIGINT NOT NULL DEFAULT 0,
    operator VARCHAR(64) NOT NULL,
    request_no VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    create_by VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(64),
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_prescription_order_eye UNIQUE (order_id, eye),
    CONSTRAINT chk_prescription_eye CHECK (eye IN ('L', 'R')),
    CONSTRAINT chk_prescription_axis CHECK (axis IS NULL OR (axis BETWEEN 1 AND 180))
);

-- 操作记录（冲销、恢复、状态流转、建档、修改全部留痕，只增不改）
CREATE TABLE IF NOT EXISTS t_op_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_type VARCHAR(24) NOT NULL,                        -- LENS / PROCESS_ORDER
    biz_id BIGINT NOT NULL,
    biz_no VARCHAR(32),                                   -- 镜片编码 / 加工单号
    action VARCHAR(24) NOT NULL,                          -- CREATE/UPDATE/REVOKE/RESTORE/STATUS_CHANGE
    before_status VARCHAR(16),
    after_status VARCHAR(16),
    detail VARCHAR(1000),
    operator VARCHAR(64) NOT NULL,
    request_no VARCHAR(64) NOT NULL,
    biz_time TIMESTAMP NOT NULL,
    version_no BIGINT NOT NULL DEFAULT 0,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_op_log_biz ON t_op_log (biz_type, biz_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('biz-1', '眼镜店 F1：镜片基础信息、加工单与处方、操作留痕');
